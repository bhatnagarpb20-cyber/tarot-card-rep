/**
 * Creates or refreshes art/manifest.json from the locked style spec and card definitions.
 * Prompts, alt text and symbols are regenerated; production state (generation, assets, review,
 * corrections) is preserved. Run: npm run art:manifest
 */
import path from "node:path";
import { buildAlt, buildPrompt, loadArtCards, loadSpec, readManifest, writeManifest, writeRegistry, type Manifest, type ManifestEntry } from "./lib";

const INITIAL_REJECTED: Manifest["rejectedSubmissions"] = [
  {
    file: "art/reference/user-collage-2026-10-21.webp",
    receivedAt: "2026-10-21",
    reason: "A single 1536×1024 collage of 78 thumbnails cannot be used as 78 individual production assets (brief rule). Kept only as a composition reference board; no card was cropped from it.",
    issues: [
      "Each card is roughly 115×190 px — far below the 1024×1536 minimum source size.",
      "Style does not match the spec: flat line art on ivory parchment instead of painterly midnight-navy Celestial Art Nouveau with antique-gold frames.",
      "Major Arcana grid has 24 cells for 22 cards: 'THE EMPERANT' appears at V where The Hierophant belongs; IX is used twice (Wheel of Fortune labelled IX); a second 'THE LOVERS' is labelled X; a garbled 'THE W…' title duplicates XX.",
      "Minor Arcana title typo: 'KING OF WORDS' for King of Wands.",
      "Nude figures in The Lovers, The Devil and The Star conflict with the deck's draped treatment.",
      "Baked-in titles use inconsistent placement and cannot be corrected without regenerating each card.",
    ],
  },
];

/** Production history recorded before this manifest existed. */
const INITIAL_GENERATION: Record<string, Partial<ManifestEntry["generation"]>> = {
  "major-00-the-fool": {
    status: "generated",
    tool: "Canva generate-image (via Canva connector)",
    reference: "Canva media MAHYpKCwVBs (1024×1536)",
    generatedAt: "2026-10-21T13:00:00Z",
    notes:
      "Generated from an early version of the prompt. The full-resolution file could not be downloaded because this environment's network policy blocks media.canva.com; only a 133×200 thumbnail was reachable, so nothing has been ingested. Thumbnail-level check: traveller at cliff edge, white rose raised, bundle on staff, white dog, sun upper right and distant mountains are all present.",
  },
};

function main() {
  const spec = loadSpec();
  const cards = loadArtCards();
  const existing = readManifest();
  const prev = new Map(existing?.cards.map((c) => [c.id, c]));

  const entries: ManifestEntry[] = cards.map((card) => {
    const old = prev.get(card.id);
    const seed = INITIAL_GENERATION[card.id];
    return {
      id: card.id,
      name: card.name,
      filename: card.id,
      expectedSource: `art/source/${card.id}.png`,
      prompt: buildPrompt(card, spec),
      alt: buildAlt(card),
      symbols: card.symbols,
      deviations: card.notes ? [card.notes] : [],
      specVersion: spec.version,
      generation: old?.generation ?? { status: "not_started", tool: null, reference: null, generatedAt: null, notes: null, ...seed },
      assets: old?.assets ?? null,
      review: old?.review ?? {
        status: "not_reviewed",
        checks: { consistency: null, symbolism: null, readability: null, cropping: null, color: null, suitDetails: null },
        reviewer: null,
        reviewedAt: null,
        notes: null,
      },
      corrections: old?.corrections ?? [],
    };
  });

  const manifest: Manifest = {
    $comment:
      "Illustration production manifest for all 78 cards. Generated by scripts/art/build-manifest.ts; production fields are updated by scripts/art/process.ts and by reviewers. `assets` stays null until real files exist.",
    specVersion: spec.version,
    updatedAt: "",
    summary: {},
    rejectedSubmissions: existing?.rejectedSubmissions ?? INITIAL_REJECTED,
    cards: entries,
  };
  writeManifest(manifest);
  writeRegistry(manifest, spec);
  console.log(`Manifest written with ${entries.length} cards → ${path.relative(process.cwd(), "art/manifest.json")}`);
  console.log(manifest.summary);
}

main();
