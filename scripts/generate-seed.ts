/**
 * Writes supabase/seed.sql from the TypeScript content (cards, courses, lessons), so the database
 * reference tables always match the code. Run: npm run db:seed:generate
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { DECK } from "@/content/cards";
import { COURSES } from "@/content/academy";
import { validateDeck } from "@/lib/tarot/validate";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function buildSeedSql(): string {
  const problems = validateDeck(DECK);
  if (problems.length) throw new Error(`Deck invalid:\n${problems.join("\n")}`);

  const lines: string[] = [
    "-- Generated by scripts/generate-seed.ts — do not edit by hand.",
    "begin;",
  ];
  for (const card of DECK) {
    const { id, name, arcana, suit, number, contentVersion, ...rest } = card;
    const content = JSON.stringify({ ...rest, numeral: card.numeral });
    lines.push(
      `insert into public.tarot_cards (id, name, arcana, suit, number, content, content_version) values (${q(id)}, ${q(name)}, ${q(arcana)}, ${suit ? q(suit) : "null"}, ${number}, ${q(content)}::jsonb, ${q(contentVersion)})` +
        ` on conflict (id) do update set name = excluded.name, content = excluded.content, content_version = excluded.content_version, updated_at = now();`,
    );
  }
  COURSES.forEach((course, ci) => {
    lines.push(
      `insert into public.learning_courses (id, title, description, position) values (${q(course.id)}, ${q(course.title)}, ${q(course.description)}, ${ci + 1})` +
        ` on conflict (id) do update set title = excluded.title, description = excluded.description, position = excluded.position;`,
    );
    course.lessons.forEach((lesson, li) => {
      lines.push(
        `insert into public.learning_lessons (id, course_id, position, title, content_version) values (${q(lesson.id)}, ${q(course.id)}, ${li + 1}, ${q(lesson.title)}, ${q(lesson.contentVersion)})` +
          ` on conflict (id) do update set course_id = excluded.course_id, position = excluded.position, title = excluded.title, content_version = excluded.content_version;`,
      );
    });
  });
  lines.push("commit;", "");
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  const out = path.resolve(__dirname, "../supabase/seed.sql");
  writeFileSync(out, buildSeedSql());
  console.log(`Wrote ${out}`);
}
